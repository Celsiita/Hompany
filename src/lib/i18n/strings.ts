/**
 * Looks up a UI string for the given locale. Supports `{n}` placeholders.
 */
export function translate(locale: AppLocale, key: string, vars?: Record<string, string | number>): string {
  let value = STRINGS[locale][key] ?? STRINGS.es[key] ?? key;
  if (vars) {
    for (const [name, raw] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(raw));
    }
  }
  return value;
}
